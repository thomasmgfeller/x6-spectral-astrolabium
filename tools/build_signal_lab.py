#!/usr/bin/env python3
"""Build/check the Signal Lab source inventory without moving research pins.

Run after an intentional source edit. --check is read-only and used by CI.
The pre-lab baseline is retained verbatim. Only the five explicitly pinned
2026-10-13 operating-window amendments are allowed; never infer approval from HEAD.
"""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = "1735a85dfd5bdb7a4b59e5c00595d2d300ce1e05"
APP_SHA = "f3795c05292b0fc6d144b7afcf7ef4a957d88ac38ab4fda0c1e985f4455eadb8"
PROTECTED_MAP_SHA = "91fb5b68fd04650be82e272d4ea607a8eda0f52165e3e65fb5555d20a5fd1c66"
RUNTIME = ["app/signal-lab-core.js", "app/signal-lab-evidence.js", "app/signal-lab-ui.js",
           "app/signal-lab.html", "app/signal-lab.css"]
INTEGRATION = ["index.html", "README.md", "tests/python/verify_manifest.py"]
# Explicit maintainer-authorised repair; no app, data adapter or math algorithm changes.
# Original digests remain in protected_research_baseline in the source manifest.
AUTHORISED_WINDOW_UPDATES = {
    ".github/workflows/x6-data-agent.yml": "b5d1c96c3ac8fa7c629e6240b09b1993cc6c893b679070721c79a707d001519e",
    ".github/workflows/x6-math-agent.yml": "c739f1a95b5dbdb9f90df012d9e9659a5f716b6d9b1b20d7d1e9a7343a6ef662",
    ".github/workflows/x6-source-agents.yml": "e8dd7f84b0e528a9bdcd13d3d5d7aa14bbd772635cc183b43226bdba4a50ca78",
    "agent/math-agent-config.json": "182d8cacf13a6e2387bf9a190e0a8f846fce531bf8157e5ba6a47eba5096317e",
    "agent/run_math_agent.py": "14867b1dbe66d925177395820c0ed0ff36b8a164ec499cb1aee5c8e4e54f99df"
}



def sha(data):
    return hashlib.sha256(data).hexdigest()


def canonical(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True, allow_nan=False)


def encoded(value):
    return (json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode()


def protected_baseline(existing, check):
    if not existing or existing.get("base_commit") != BASE:
        raise ValueError("missing reviewed research baseline")
    baseline = existing.get("protected_research_baseline")
    if not isinstance(baseline, dict) or sha(canonical(baseline).encode()) != PROTECTED_MAP_SHA:
        raise ValueError("original 17-file research baseline changed")
    protected = {**baseline, **AUTHORISED_WINDOW_UPDATES}
    if existing.get("protected_research") != protected:
        raise ValueError("research inventory differs from the explicitly authorised amendment")
    for name, expected in protected.items():
        path = ROOT / name
        if path.is_symlink() or not path.is_file() or sha(path.read_bytes()) != expected:
            raise ValueError("protected research source changed: " + name)
    config = json.loads((ROOT / "agent/math-agent-config.json").read_text())
    if config["app_sha256"] != APP_SHA:
        raise ValueError("research app pin changed")
    return protected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    manifest_path = ROOT / "SIGNAL_LAB_SOURCE_MANIFEST.json"
    existing = json.loads(manifest_path.read_text()) if manifest_path.exists() else None
    protected = protected_baseline(existing, args.check)
    if sha((ROOT / "app/index.html").read_bytes()) != APP_SHA:
        raise ValueError("protected Astrolabium app changed")
    version = subprocess.check_output(["node", "-e", "process.stdout.write(require('./app/signal-lab-core.js').VERSION)"], cwd=ROOT, text=True)
    runtime = {name: sha((ROOT / name).read_bytes()) for name in sorted(RUNTIME)}
    build = {
        "schema": "x6.signal-lab.build/1",
        "version": version,
        "base_commit": BASE,
        "source_status": "DECLARED_BUILD_MANIFEST",
        "protected_app_sha256": APP_SHA,
        "bundle_algorithm": "SHA-256 of sorted compact UTF-8 JSON file-to-SHA-256 mapping",
        "bundle_sha256": sha(canonical(runtime).encode()),
        "files": runtime,
    }
    build_bytes = ("/* Generated by tools/build_signal_lab.py; declared source inventory, not a signature. */\n"
                   "(function(root){'use strict';const build=" + json.dumps(build, indent=2) + ";\n"
                   "Object.freeze(build.files);Object.freeze(build);\n"
                   "if(typeof module==='object'&&module.exports)module.exports=build;else root.X6SignalLabBuild=build;\n"
                   "})(typeof globalThis!=='undefined'?globalThis:this);\n").encode()
    files = set(RUNTIME + ["app/signal-lab-build.js", "tools/build_signal_lab.py",
                          ".github/workflows/x6-signal-lab.yml"])
    for pattern in ["tests/signal-lab/*.cjs", "tests/signal-lab/*.py", "tests/signal-lab/*.txt",
                    "docs/SIGNAL_LAB*.md", "docs/SIGNAL_VALIDATION_LAB.md"]:
        files.update(str(p.relative_to(ROOT)) for p in ROOT.glob(pattern) if p.is_file())
    hashes = {name: sha(build_bytes if name == "app/signal-lab-build.js" else (ROOT / name).read_bytes()) for name in sorted(files)}
    manifest = {
        "schema": "x6.signal-lab.source-manifest/1", "algorithm": "sha256", "base_commit": BASE,
        "scope": "Isolated Signal Validation Lab implementation and qualification sources. Content inventory only; not authenticity or scientific certification.",
        "protected_research_baseline": existing["protected_research_baseline"],
        "protected_research": protected,
        "files": hashes,
    }
    sagnac_path = ROOT / "SAGNAC_SOURCE_MANIFEST.json"
    sagnac = json.loads(sagnac_path.read_text())
    for name, expected in sagnac["files"].items():
        actual = sha((ROOT / name).read_bytes())
        if name in INTEGRATION:
            sagnac["files"][name] = actual
        elif actual != expected:
            raise ValueError("unrelated Sagnac/photonic source changed: " + name)
    outputs = {ROOT / "app/signal-lab-build.js": build_bytes,
               manifest_path: encoded(manifest), sagnac_path: encoded(sagnac)}
    if args.check:
        differences = [str(path.relative_to(ROOT)) for path, value in outputs.items()
                       if not path.is_file() or path.read_bytes() != value]
        if differences:
            raise ValueError("stale declared build/inventory: " + ", ".join(differences))
    else:
        for path, value in outputs.items():
            path.write_bytes(value)
    print(json.dumps({"status": "PASS" if args.check else "GENERATED", "runtime_files": len(runtime),
                      "lab_sources": len(hashes), "protected_research_files": len(protected),
                      "bundle_sha256": build["bundle_sha256"]}, indent=2))


if __name__ == "__main__":
    main()
