"""Poset enumeration for one new zero-weight station."""

LAYERS=(1,-9,16,-8)
MATERIAL=set(range(19))-{15,17}


def ideals(order,nodes):
    past={j:{i for i,k in order if k==j} for j in nodes}
    listed=sorted(nodes,key=lambda j:len(past[j]))
    result=[frozenset()]
    for j in listed:
        result += [s|{j} for s in result if past[j]<=s]
    return set(result)


def antichain_generators(order,nodes):
    # Closures of all antichains give all downsets; an empty generator is allowed.
    subsets=[frozenset()]
    for j in sorted(nodes):
        subsets += [s|{j} for s in subsets if all((i,j) not in order and (j,i) not in order for i in s)]
    return {s|{i for i,j in order if j in s} for s in subsets}


def coefficients(order,future):
    weights={}
    for j in future:
        n=sum((k,j) in order for k in future)
        if n<len(LAYERS):
            weights[j]=LAYERS[n]
    return weights


def enumerate_extensions(order):
    nodes=set(range(19))
    reverse={(j,i) for i,j in order}
    down=ideals(order,nodes)
    up=ideals(reverse,nodes)
    assert down==antichain_generators(order,nodes)
    assert up==antichain_generators(reverse,nodes)
    all_records=[]
    kept=[]
    for p in sorted(down,key=lambda s:tuple(sorted(s))):
        for f in sorted(up,key=lambda s:tuple(sorted(s))):
            if not p.isdisjoint(f) or not all((i,j) in order for i in p for j in f):
                continue
            all_records.append((p,f))
            anchors={}
            for m in (16,18):
                if m in p or m in f: continue
                pairs=sorted((a,b) for a in p&MATERIAL if (a,m) in order
                             for b in f&MATERIAL if (m,b) in order)
                if pairs:anchors[m]=pairs
            if anchors:kept.append((p,f,anchors))
    # All ternary roles generated by inserting the new point between two nested
    # ideals. The complement of the second is its future.
    independent={(x,frozenset(nodes-y)) for x in down for y in down
                 if x<=y and all((i,j) in order for i in x for j in nodes-y)}
    assert set(all_records)==independent
    return len(all_records),kept


def two_station_register(order):
    """Count labelled pairs of one-point records with common anchors and no cross-comparison."""
    nodes=set(range(19))
    down=ideals(order,nodes)
    up=ideals({(j,i) for i,j in order},nodes)
    mask=lambda s:sum(1<<i for i in s)
    records=[(mask(p),mask(f)) for p in down for f in up
             if p and f and p.isdisjoint(f) and all((i,j) in order for i in p for j in f)]
    material=mask(MATERIAL);early=mask({0,1,2,3});late=mask({7,8,9,10});devices=mask({15,16,17,18})
    total=collar_order=survived_density=survived_empty=0
    for pn,fn in records:
        for pz,fz in records:
            if (fn & pz) or (fz & pn):continue
            if not ((pn & pz & material) and (fn & fz & material)):continue
            total+=1
            if ((pn|pz)&late) or ((fn|fz)&early):continue
            collar_order+=1
            if not pn&devices:continue
            survived_density+=1
            if not fz&~late:continue
            survived_empty+=1
    return dict(common_anchors_total=total,after_boundary_time_order=collar_order,
                after_positive_past_test=survived_density,after_pure_collar_future_test=survived_empty)
