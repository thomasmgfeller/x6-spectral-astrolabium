#!/usr/bin/env python3
"""Preserved archive/source parity and the original isolated scientific replay."""
from pathlib import Path
import hashlib
import json
import subprocess
import sys
import zipfile

HERE=Path(__file__).resolve().parent
ROOT=HERE/'interference_dynamics_v0_1'
STEM='CST_DUST_Interferenz_Dynamik_v0_1'

def require(condition,message):
    if not condition:
        raise RuntimeError(message)

def main():
    require(not sys.flags.optimize,'Do not disable scientific assertions with python -O.')
    record=json.loads((HERE/'interference_dynamics_publication.json').read_text())
    for item in record['artifacts']:
        data=(HERE/item['path']).read_bytes()
        require(len(data)==item['bytes'],'Size mismatch: '+item['path'])
        require(hashlib.sha256(data).hexdigest()==item['sha256'],'Hash mismatch: '+item['path'])
    source_manifest=json.loads((ROOT/'MANIFEST.json').read_text())
    entries=source_manifest['files']
    paths={entry['path'] for entry in entries}|{'MANIFEST.json'}
    require(len(paths)==len(entries)+1,'Duplicate manifest path')
    with zipfile.ZipFile(HERE/'packages'/(STEM+'_Pruefpaket.zip')) as archive:
        archive_manifest=json.loads(archive.read(ROOT.name+'/MANIFEST.json'))
        archive_entries=archive_manifest['files']
        archive_paths={item['path'] for item in archive_entries}|{'MANIFEST.json'}
        omitted=set(record['expanded_source_cleanup']['omitted_archive_paths'])
        require(omitted=={'checks/full_weight/__pycache__/check.cpython-312.pyc'},'Unexpected cleanup scope')
        require(paths==archive_paths-omitted,'Unexpected expanded source inventory')
        require(len(archive_paths)==len(archive_entries)+1,'Duplicate archive manifest path')
        require(source_manifest=={**archive_manifest,'files':[e for e in archive_entries if e['path'] not in omitted]},'Unexpected derived source manifest')
        expected={ROOT.name+'/'+path for path in archive_paths}
        require(archive.testzip() is None,'ZIP CRC failure')
        require(len(archive.namelist())==len(expected) and set(archive.namelist())==expected,'ZIP inventory mismatch')
        for item in archive_entries:
            data=archive.read(ROOT.name+'/'+item['path'])
            require(len(data)==item['bytes'] and hashlib.sha256(data).hexdigest()==item['sha256'],'Original archive entry mismatch: '+item['path'])
        for path in paths-{'MANIFEST.json'}:
            require(archive.read(ROOT.name+'/'+path)==(ROOT/path).read_bytes(),'ZIP/source mismatch: '+path)
    require((HERE/'reports'/(STEM+'.pdf')).read_bytes()==(ROOT/'report/CST_DUST_Interferenz_Randantwort_Dynamikpruefung_v0_1.pdf').read_bytes(),'PDF copy mismatch')
    print(f'PASS: {len(archive_paths)} original ZIP entries; {len(paths)} expanded files, only generated bytecode omitted; source manifest derived; identical report copies.',flush=True)
    subprocess.run([sys.executable,'-B',str(ROOT/'verify.py')],check=True)

if __name__=='__main__':main()
